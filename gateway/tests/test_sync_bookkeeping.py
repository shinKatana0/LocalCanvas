def test_the_value_shape_questions_are_still_asked_first() -> None:
    """Placement, proved rather than asserted in a paragraph.

    The branch is after the media question and after both questions about the
    shape of the value.  So an input carrying one of these names *and* a value
    an earlier branch can read is still answered by that earlier branch -- and
    a branch inserted higher up would take those two verdicts away.
    """

    assert classify("upload", "adapter.safetensors") == Verdict(
        Exposure.LOCKED,
        "input 'upload' names a file of weights to load; which file loads is "
        "what the workflow *is*, not how it generates.",
        kind="weights_file",
    )
    assert classify("upload", "C:/somewhere/else/photo.png") == Verdict(
        Exposure.LOCKED,
        "input 'upload' holds a path on this machine; LocalCanvas never puts a "
        "filesystem path in front of a user.",
        kind="filesystem_path",
    )


def test_no_other_vocabulary_in_the_module_claims_these_words() -> None:
    """The other half of the placement claim, and the one that can rot.

    Every branch below the new one asks about the input's *name*, so if one of
    their vocabularies ever gained ``upload``, ``control``, ``after`` or
    ``generate``, the order of the two would start to decide the answer and
    the comment in ``classify()`` would quietly stop being true.  This fails
    the day that happens, which is the day someone would want to know.
    """

    ours: Set[str] = set()
    for entry in BOOKKEEPING_INPUT_NAMES:
        ours |= set(entry.split("_"))

    for label, other in (
        ("LOCKED_ANY_WORDS", semantics.LOCKED_ANY_WORDS),
        ("LOCKED_STRING_WORDS", semantics.LOCKED_STRING_WORDS),
        ("PROMPT_WORDS", semantics.PROMPT_WORDS),
        ("SAFE_STRING_WORDS", semantics.SAFE_STRING_WORDS),
        ("MEDIA_WORDS", semantics.MEDIA_WORDS),
        ("MASK_WORDS", semantics.MASK_WORDS),
    ):
        assert ours & set(other) == set(), label


