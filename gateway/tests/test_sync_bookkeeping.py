def test_the_table_above_reaches_every_branch_of_classify() -> None:
    """A table that missed a branch would leave that branch unguarded.

    Checked by the shape of the answers rather than by counting rows: every
    exposure, every locking slug the module can return, and both of the two
    ``EXPOSE`` shapes that carry no field id.
    """

    verdicts = [classify(case.values[0], case.values[1]) for case in UNCHANGED]

    assert {verdict.exposure for verdict in verdicts} == set(Exposure)
    assert {verdict.kind for verdict in verdicts if verdict.kind} == {
        "weights_file",
        "filesystem_path",
        "machine_setting",
        "file_reference",
    }
    assert {verdict.field_type for verdict in verdicts if verdict.exposed} == {
        "image",
        "video",
        "multiline",
        "integer",
        "float",
        "boolean",
        "string",
    }
    assert any(verdict.prompt for verdict in verdicts)
    assert any(verdict.mask for verdict in verdicts)


