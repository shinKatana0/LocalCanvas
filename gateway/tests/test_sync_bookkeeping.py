def bookkeeping_graph() -> Dict[str, Any]:
    """One importable graph carrying both bookkeeping inputs.

    Every node type is invented here.  The picture, the prompt and the two
    numbers are real controls, so the disjointness below is measured against
    a definition that genuinely binds something.
    """

    return {
        "1": {
            "class_type": "ExampleWeightsLoader",
            "inputs": {"ckpt_name": "chosen-weights.safetensors"},
        },
        "2": {
            "class_type": "ExamplePictureLoader",
            "inputs": {"image": "a photo.png", "upload": "image"},
        },
        "3": {
            "class_type": "ExampleTextEncode",
            "inputs": {"text": "a quiet street at dawn", "clip": ["1", 1]},
        },
        "4": {
            "class_type": "ExampleSampler",
            "inputs": {
                "seed": 12345,
                "control_after_generate": "randomize",
                "steps": 24,
                "model": ["1", 0],
                "positive": ["3", 0],
                "pixels": ["2", 0],
            },
        },
        "5": {
            "class_type": "ExampleSave",
            "inputs": {"filename_prefix": "generated", "images": ["4", 0]},
        },
    }


def imported(workspace: SyncWorkspace, graph: Dict[str, Any]):
    folder = workspace.add_source()
    write_json(folder / "one.json", graph)
    workspace.write_config()
    report = run_sync(workspace.load(), now=FIXED)
    registry = load_registry(workspace.repo / "config" / "local" / "workflows")
    return report, registry


def test_bookkeeping_is_reported_with_its_section_slug_and_reason() -> None:
    """T-0069's property: recognised and decided, rather than silently dropped."""

    plan = analyse(bookkeeping_graph())
    entries = {(item.node, item.input): item for item in plan.controls}

    for node, name in (("2", "upload"), ("4", "control_after_generate")):
        target = (node, name)
        entry = entries[target]
        assert entry.section == "locked", target
        assert entry.kind == "editor_bookkeeping", target
        assert entry.reason == bookkeeping_reason(name), target
        assert entry.field is None, target
        assert entry.label is None, target

    assert [
        (item.node, item.input, item.kind)
        for item in plan.not_exposed
        if item.kind == "editor_bookkeeping"
    ] == [
        ("2", "upload", "editor_bookkeeping"),
        ("4", "control_after_generate", "editor_bookkeeping"),
    ]


def test_bookkeeping_never_reaches_a_binding(workspace: SyncWorkspace) -> None:
    """Presence first, then absence, so the absence cannot pass vacuously.

    The two pairs are asserted to be in the inventory as hidden; then the
    definition is asserted to bind something at all; only then is the
    intersection asserted empty.
    """

    _, registry = imported(workspace, bookkeeping_graph())
    plan = analyse(bookkeeping_graph())
    hidden: Set[Tuple[str, str]] = {
        (item.node, item.input)
        for item in plan.controls
        if item.section in HIDDEN_SECTIONS
    }

    assert {("2", "upload"), ("4", "control_after_generate")} <= hidden

    bound = {
        (binding.node, binding.input)
        for workflow in registry.workflows
        for field in workflow.inputs
        for binding in workflow.bindings_for(field.id)
    }
    assert bound == {("2", "image"), ("3", "text"), ("4", "seed"), ("4", "steps")}
    assert bound & hidden == set()


def test_no_bookkeeping_name_or_value_reaches_the_view_the_app_receives(
    workspace: SyncWorkspace,
) -> None:
    """The inventory is a curator's document; the app is served another one."""

    _, registry = imported(workspace, bookkeeping_graph())

    view = json.dumps(registry.workflows[0].detail_view())
    for hidden in ("upload", "control_after_generate", "randomize"):
        assert hidden not in view, hidden


