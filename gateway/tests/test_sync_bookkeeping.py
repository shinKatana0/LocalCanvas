"""ComfyUI's own bookkeeping is not a control the user refused to explain.

``upload`` is a value ComfyUI writes into the API export of an image loader,
and ``control_after_generate`` one it writes beside a seed.  Neither is a
setting anybody chose, so neither could ever be proved safe *or* structural
by the questions this module asks -- and one UNCERTAIN input takes its whole
workflow to ``NEEDS_REVIEW``.  Measured on this repository's own
``example_img2img_api.json``, which is the shape of every img2img, inpaint,
edit and upscale-from-file export there is.

What is **not** broken, and is not touched here: the importer's refusal to
guess at a string it cannot read (T-0054).  The fix is upstream of that rule.

Two guards, each failing on its own -- and each on a *different* mutation:

* **remove the branch** and the verdict tests, the example test and the
  inventory test die, because the two names go back to UNCERTAIN;
* **make the branch match word tokens instead of whole names** and the
  whole-name tests and the unchanged-verdict table die, because ``upload``
  would then reach ``upload_strength`` and ``control`` would reach every
  ``control_*`` a node genuinely offers.  Neither of those is caught by the
  first mutation, and the verdict tests are not caught by the second: a token
  match still returns the same verdict for the two real names.

The last section is the one that says this card changed nothing else: every
verdict in ``UNCHANGED`` was generated by running the **parent commit's**
``semantics.py`` over the same inputs, so it is the old module's own answer
and not something typed from memory.

No graph invented here names a model, a family, a vendor or a node pack,
and nothing in this file was learned from any ComfyUI installation.
"""

