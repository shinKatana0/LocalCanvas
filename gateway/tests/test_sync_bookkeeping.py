def test_a_bookkeeping_name_is_locked_whatever_type_its_value_holds() -> None:
    """The behaviour this card changed beyond the two measured strings.

    The branch is keyed on the input's **name**, so one of these names holding
    a number or a flag is locked as well.  Before this card rule 6 answered
    first for those and exposed them as a field a user could set.  That change
    is the intended semantics of a name-keyed rule -- the name is the whole of
    the evidence, and rule 6 never looks at it -- but it is a real change, and
    a real change with no guard on it is one that rots unnoticed.

    Not vacuous: the numeric and boolean rows of ``UNCHANGED``,
    ``test_the_number_a_user_may_tune_is_still_a_number`` and the
    ``upload_strength``, ``control_scale`` and ``generate_batch`` hazards above
    all say that rule 6 still exposes a number or a flag whose name is *not*
    one of these two -- including three that merely contain a word of one.
    """

    assert classify("upload", 0) == Verdict(
        Exposure.LOCKED,
        bookkeeping_reason("upload"),
        kind="editor_bookkeeping",
    )
    assert classify("control_after_generate", True) == Verdict(
        Exposure.LOCKED,
        bookkeeping_reason("control_after_generate"),
        kind="editor_bookkeeping",
    )


def test_the_slug_is_one_the_frozen_set_knows() -> None:
    """A slug no ``LOCKED_KINDS`` member matches would be a private taxonomy."""

    verdict = classify("upload", "image")

    assert verdict.kind in LOCKED_KINDS
    assert verdict.exposure is Exposure.LOCKED


