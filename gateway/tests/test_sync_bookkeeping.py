@pytest.mark.parametrize("name,value,expected", TOKEN_HAZARDS)
def test_a_control_that_merely_contains_one_of_these_words_is_untouched(
    name: str, value: Any, expected: Verdict
) -> None:
    assert classify(name, value) == expected


def test_the_hazard_names_really_do_contain_the_vocabulary_words() -> None:
    """The fixture check: without it the test above proves nothing.

    If none of those four names shared a word with the vocabulary, a token
    match would leave them alone too and the guard could never fire.
    """

    vocabulary_words: Set[str] = set()
    for entry in BOOKKEEPING_INPUT_NAMES:
        vocabulary_words |= set(entry.split("_"))

    for case in TOKEN_HAZARDS:
        name = case.values[0]
        assert set(name.split("_")) & vocabulary_words, name


def test_the_vocabulary_is_matched_entire_and_case_foldingly() -> None:
    """The same complete name written another way is still that name.

    Normalising case and the character between the words is not a token match
    and must not be read as licence for one: the name is compared whole.
    """

    for spelling in ("upload", "Upload", "UPLOAD"):
        assert classify(spelling, "image").kind == "editor_bookkeeping", spelling
    for spelling in ("control_after_generate", "control-after-generate"):
        assert classify(spelling, "randomize").kind == "editor_bookkeeping", spelling

    # ...and a name that is merely *near* one of them is not one of them.
    assert classify("uploads", "image").kind is None
    assert classify("control_after_generation", "randomize").kind is None


